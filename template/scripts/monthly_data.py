"""Build src/howmuch/monthly-data.ts for the monthly "map update" Reel.

Input: a JSON file (see data/monthly/2026-10.json) with
  month_en / month_de: labels ("October 2026" / "Oktober 2026")
  next_en / next_de: date of next update
  rows: SQL rows [{loc, new_places, prices}] where loc = Vienna postal-code Bezirk ("07") or "lat,lng"
  owner_confirmed: prices confirmed by owners this month
  moves: like-for-like price changes [{label, up, down}] (same place + product + variant), may be empty
GPS rows are assigned with data/vienna-districts.geo.json (data.wien.gv.at, CC BY 4.0).
Usage: python3 -I scripts/monthly_data.py data/monthly/2026-10.json
"""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = json.load(open(sys.argv[1]))
geo = json.load(open(root / "data/vienna-districts.geo.json"))

def inside(x, y, ring):
    c = False; j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][:2]; xj, yj = ring[j][:2]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi: c = not c
        j = i
    return c
def rings(v):
    out = []
    def walk(x):
        if isinstance(x[0][0], (int, float)): out.append(x)
        else:
            for y in x: walk(y)
    walk(v); return out
def bezirk(loc):
    if "," not in loc: return int(loc)
    lat, lng = map(float, loc.split(","))
    for k, v in geo.items():
        if any(inside(lng, lat, r) for r in rings(v)): return int(k)
    return None

per = {n: {"prices": 0, "places": 0} for n in range(1, 24)}
for r in src["rows"]:
    b = bezirk(r["loc"])
    if b is None: continue
    per[b]["prices"] += int(r["prices"]); per[b]["places"] += int(r["new_places"])
out = {k: src[k] for k in ("month_en", "month_de", "next_en", "next_de", "owner_confirmed", "moves")}
out["per"] = per
out["prices"] = sum(p["prices"] for p in per.values())
out["places"] = sum(p["places"] for p in per.values())
ts = "// Generated by scripts/monthly_data.py: do not edit by hand\nexport const MONTH = " + json.dumps(out, ensure_ascii=False) + " as const;\n"
(root / "src/howmuch/monthly-data.ts").write_text(ts)
print(out["prices"], out["places"], {k: v for k, v in per.items() if v["prices"] or v["places"]})
