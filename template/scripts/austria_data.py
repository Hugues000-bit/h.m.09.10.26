"""Build src/howmuch/austria-data.ts for the "Austria" monthly Reel (AustriaMonthly.tsx).

Input: a JSON file (see data/austria/2026-11.json) with
  month_en / month_de / next_en / next_de: labels
  points: "lat,lng,new_place,prices_this_month;..." one entry per active place that has an active price
          (query in the skill: SQL "Austria monthly"). new_place = 1 if the place was created this month.
Each place is assigned to the nearest city in CITIES within its radius; others are ignored.
Map outline: data/austria-outline.geo.json (Natural Earth 1:10m, public domain).
Vienna detail: data/vienna-districts.geo.json (data.wien.gv.at, CC BY 4.0).

Usage:
  python3 -I scripts/austria_data.py data/austria/2026-12.json
  python3 -I scripts/austria_data.py data/austria/2026-11.json --demo   # adds FAKE Graz/Linz points to test the layout;
                                                                         # the video then shows a DEMO watermark. Never post.
"""
import json, sys, math, random, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
demo = "--demo" in sys.argv
src = json.load(open(args[0]))

# key, name EN, name DE, lat, lng, radius km
CITIES = [
    ("wien", "Vienna", "Wien", 48.2082, 16.3738, 16),
    ("graz", "Graz", "Graz", 47.0707, 15.4395, 12),
    ("linz", "Linz", "Linz", 48.3069, 14.2858, 12),
    ("salzburg", "Salzburg", "Salzburg", 47.8095, 13.0550, 12),
    ("innsbruck", "Innsbruck", "Innsbruck", 47.2692, 11.4041, 12),
    ("klagenfurt", "Klagenfurt", "Klagenfurt", 46.6249, 14.3050, 12),
    ("stpoelten", "St. Pölten", "St. Pölten", 48.2047, 15.6256, 10),
    ("villach", "Villach", "Villach", 46.6111, 13.8558, 10),
    ("wels", "Wels", "Wels", 48.1575, 14.0289, 8),
    ("dornbirn", "Dornbirn", "Dornbirn", 47.4125, 9.7417, 8),
    ("bregenz", "Bregenz", "Bregenz", 47.5031, 9.7471, 8),
    ("eisenstadt", "Eisenstadt", "Eisenstadt", 47.8456, 16.5233, 8),
]

def km(a, b, c, d):
    x = math.radians(d - b) * math.cos(math.radians((a + c) / 2)); y = math.radians(c - a)
    return 6371 * math.hypot(x, y)

pts = []
for e in src["points"].split(";"):
    if not e.strip(): continue
    lat, lng, np, pr = e.split(",")
    pts.append((float(lat), float(lng), int(np), int(pr)))

if demo:  # FAKE points around Graz (40 places) and Linz (4) — layout test only
    rnd = random.Random(7)
    for i in range(40):
        pts.append((47.0707 + rnd.gauss(0, 0.012), 15.4395 + rnd.gauss(0, 0.018), 1, rnd.randint(1, 6)))
    for i in range(4):
        pts.append((48.3069 + rnd.gauss(0, 0.01), 14.2858 + rnd.gauss(0, 0.015), 1, 2))

# projection: equirectangular, cos(lat0) correction, scaled to W px
geo = json.load(open(root / "data/austria-outline.geo.json"))["geometry"]
ring = geo["coordinates"][0] if geo["type"] == "Polygon" else max((p[0] for p in geo["coordinates"]), key=len)
lons = [p[0] for p in ring]; lats = [p[1] for p in ring]
lat0 = (min(lats) + max(lats)) / 2; cl = math.cos(math.radians(lat0))
W = 820
k = W / ((max(lons) - min(lons)) * cl)
H = (max(lats) - min(lats)) * k
P = lambda lng, lat: (round((lng - min(lons)) * cl * k, 3), round((max(lats) - lat) * k, 3))
def path(r):
    return "M" + "L".join("%s,%s" % P(*p[:2]) for p in r) + "Z"
outline = path(ring)
vd = json.load(open(root / "data/vienna-districts.geo.json"))
def rings(v):
    out = []
    def walk(x):
        if isinstance(x[0][0], (int, float)): out.append(x)
        else:
            for y in x: walk(y)
    walk(v); return out
vienna = "".join(path(r) for v in vd.values() for r in rings(v))

cities = []
for key, en, de, la, lo, rad in CITIES:
    mine = []
    for p in pts:
        best = min(CITIES, key=lambda c: km(p[0], p[1], c[3], c[4]))
        if best[0] == key and km(p[0], p[1], la, lo) <= rad: mine.append(p)
    if not mine: continue
    x, y = P(lo, la)
    cities.append({
        "key": key, "name": en, "nameDe": de, "x": x, "y": y,
        "total": len(mine),
        "newPrices": sum(p[3] for p in mine),
        "newPlaces": sum(p[2] for p in mine),
        "pts": [[*P(p[1], p[0]), 1 if (p[2] or p[3]) else 0] for p in mine],
    })
cities.sort(key=lambda c: -c["newPrices"])
out = {k2: src[k2] for k2 in ("month_en", "month_de", "next_en", "next_de")}
out.update({"demo": demo, "W": W, "H": round(H, 2), "outline": outline, "vienna": vienna, "cities": cities})
ts = "// Generated by scripts/austria_data.py: do not edit by hand\nexport const AUSTRIA = " + json.dumps(out, ensure_ascii=False) + " as const;\n"
(root / "src/howmuch/austria-data.ts").write_text(ts)
for c in cities:
    print(f'{c["name"]:12} total {c["total"]:4}  +{c["newPrices"]} prices  +{c["newPlaces"]} places')
if demo: print("DEMO data: never post this render")
