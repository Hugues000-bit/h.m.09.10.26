"""Build src/howmuch/cheapest-data.ts for the "cheapest X in every Bezirk" tile map.

Input JSON (see data/cheapest/2026-10-22.json): {date_en, sets: {NAME: [{loc, mn, n}]}}
where each row is one SQL group (latest price per place, one product+variant) by loc = postal-code Bezirk ("07") or "lat,lng".
GPS rows are assigned with data/vienna-districts.geo.json (data.wien.gv.at, CC BY 4.0).
Usage: python3 -I scripts/cheapest_data.py data/cheapest/2026-10-22.json
"""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = json.load(open(sys.argv[1]))
geo = json.load(open(root / "data/vienna-districts.geo.json"))
def inside(x, y, ring):
    c = False; j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][:2]; xj, yj = ring[j][:2]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi: c = not c
        j = i
    return c
def rings(v):
    out = []
    def walk(x):
        if isinstance(x[0][0], (int, float)): out.append(x)
        else:
            for y in x: walk(y)
    walk(v); return out
def bezirk(loc):
    if "," not in loc: return int(loc)
    lat, lng = map(float, loc.split(","))
    for k, v in geo.items():
        if any(inside(lng, lat, r) for r in rings(v)): return int(k)
    return None
out = {"date_en": src["date_en"], "sets": {}}
for name, rows in src["sets"].items():
    per = {}
    for r in rows:
        b = bezirk(r["loc"])
        if b is None: continue
        mn, n = float(r["mn"]), int(r["n"])
        cur = per.get(b)
        per[b] = {"min": min(mn, cur["min"]) if cur else mn, "n": (cur["n"] if cur else 0) + n}
    out["sets"][name] = per
    print(name, sorted(per.items()))
(root / "src/howmuch/cheapest-data.ts").write_text(
    "// Generated by scripts/cheapest_data.py: do not edit by hand\nexport const CHEAPEST = " + json.dumps(out, ensure_ascii=False) + " as const;\n")
