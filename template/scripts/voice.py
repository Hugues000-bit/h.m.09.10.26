#!/usr/bin/env python3
"""Voice-over lines for the HOW MUCH?! videos.

Reads data/voice/<set>.json  ({"voice": "en-us-ryan-medium", "lines": [{"id", "say", "show"?}]}),
writes one audio file per line to public/howmuch/voice/<set>/<id>.wav (levelled, 48 kHz)
and rewrites src/howmuch/voice-data.ts with the caption text and the length of each line in frames.

  PIPER_VOICES=/path/to/onnx/models python3 scripts/voice.py higherlower mapdive

"say" is what the voice reads (numbers written out), "show" is the caption (defaults to "say").
The voice models (.onnx + .onnx.json, piper) are not in the repo: they are too large.
"""
import json, os, subprocess, sys, wave, pathlib, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
VOICES = pathlib.Path(os.environ.get("PIPER_VOICES", "."))
FPS = 30

def synth(model, text, out, speed):
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=False) as tmp:
        raw = tmp.name
    subprocess.run([sys.executable, "-m", "piper", "-m", str(model), "-f", raw, "--length-scale", str(speed), "--sentence-silence", "0.18"],
                   input=text.encode(), check=True, capture_output=True)
    # level every line the same, trim leading/trailing silence, 48 kHz mono
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", raw, "-af",
                    "silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,loudnorm=I=-16:TP=-1.5:LRA=11",
                    "-ar", "48000", "-ac", "1", str(out)], check=True)
    os.unlink(raw)
    with wave.open(str(out)) as w:
        return w.getnframes() / w.getframerate()

def main(sets):
    manifest_path = ROOT / "data" / "voice" / "_manifest.json"
    manifest = json.loads(manifest_path.read_text()) if manifest_path.exists() else {}
    for s in sets:
        spec = json.loads((ROOT / "data" / "voice" / f"{s}.json").read_text())
        model = VOICES / f"{spec['voice']}.onnx"
        out_dir = ROOT / "public" / "howmuch" / "voice" / s
        out_dir.mkdir(parents=True, exist_ok=True)
        manifest[s] = {}
        for ln in spec["lines"]:
            sec = synth(model, ln["say"], out_dir / f"{ln['id']}.wav", spec.get("speed", 1.0))
            manifest[s][ln["id"]] = {"show": ln.get("show", ln["say"]), "frames": round(sec * FPS)}
            print(f"{s}/{ln['id']}: {sec:.2f}s  {ln['say']}")
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=1))
    ts = "// Generated by scripts/voice.py — do not edit by hand.\n"
    ts += "export const VOICE: Record<string, Record<string, { show: string; frames: number }>> = "
    ts += json.dumps(manifest, ensure_ascii=False) + ";\n"
    (ROOT / "src" / "howmuch" / "voice-data.ts").write_text(ts)

if __name__ == "__main__":
    main(sys.argv[1:])
