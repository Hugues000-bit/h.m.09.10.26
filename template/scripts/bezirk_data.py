#!/usr/bin/env python3
"""Data for the district map films (LeereKarte, InnenAussen).

  python3 scripts/bezirk_data.py data/maps/2026-11-18.json

Input: aggregates only (places per Bezirk, lowest/highest price inside and outside, counts under a price).
Also tags each dot of places-data.ts (data/places/2026-11-10.json) with its Bezirk, so the films can colour
the dots by district. Writes src/howmuch/bezirk-data.ts.
"""
import json, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
LNG0, LAT1, KX, KY = 16.18, 48.325, 2500.0, 3751.5

agg = json.loads(pathlib.Path(sys.argv[1]).read_text())
geo = json.loads((ROOT / "data" / "vienna-districts.geo.json").read_text())
places = json.loads((ROOT / "data" / "places" / "2026-11-10.json").read_text())


def inside(x, y, ring):
    c = False
    for i in range(len(ring)):
        x1, y1 = ring[i]
        x2, y2 = ring[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            c = not c
    return c


def bezirk(lng, lat):
    for nr, rings in geo.items():
        if sum(inside(lng, lat, r) for r in rings) % 2 == 1:
            return int(nr)
    return 0


dots = [[int(v) / 10 for v in p.split(",")] for p in places["pts"].split(";")]
dot_bez = [bezirk(x / KX + LNG0, LAT1 - y / KY) for x, y in dots]

xs, ys = [], []
for rings in geo.values():
    for ring in rings:
        for lng, lat in ring:
            xs.append((lng - LNG0) * KX)
            ys.append((LAT1 - lat) * KY)
bounds = [round(min(xs), 1), round(min(ys), 1), round(max(xs), 1), round(max(ys), 1)]

ts = "// Generated by scripts/bezirk_data.py from " + sys.argv[1] + " — do not edit by hand.\n"
ts += "// Aggregates from the howmuch.live database (no venue, no individual price).\n"
ts += "export const MAPDATA = " + json.dumps({k: v for k, v in agg.items() if not k.startswith("_")}, ensure_ascii=False) + " as const;\n"
ts += "// Bezirk of each dot of places-data.ts (0 = outside every district)\n"
ts += "export const DOT_BEZ: number[] = " + json.dumps(dot_bez) + ";\n"
ts += "// [minX, minY, maxX, maxY] of Vienna in map units\n"
ts += "export const BOUNDS = " + json.dumps(bounds) + ";\n"
(ROOT / "src" / "howmuch" / "bezirk-data.ts").write_text(ts)
print(len(dots), "dots;", sum(1 for b in dot_bez if 1 <= b <= 9), "inside 1-9;", "bounds", bounds)
