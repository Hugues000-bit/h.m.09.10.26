#!/usr/bin/env python3
"""Map data for the camera map videos (MapDive, MapFill).

  python3 scripts/places_data.py data/places/2026-11-10.json

Input (no names, no prices): "pts" = one dot per place with an active price, ordered by the date of its
first price, already projected by the SQL query as x*10,y*10 with
  x = (lng - 16.18) * 2500        y = (48.325 - lat) * 3751.5   (equirectangular, 1000 px wide)
"months" = [["2026-04", number of places first priced that month], ...].
Writes src/howmuch/places-data.ts: district outlines in the same projection + the dots.
"""
import json, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
LNG0, LAT1, KX, KY = 16.18, 48.325, 2500.0, 3751.5
NAMES = {1:"Innere Stadt",2:"Leopoldstadt",3:"Landstraße",4:"Wieden",5:"Margareten",6:"Mariahilf",7:"Neubau",8:"Josefstadt",9:"Alsergrund",10:"Favoriten",11:"Simmering",12:"Meidling",13:"Hietzing",14:"Penzing",15:"Rudolfsheim-Fünfhaus",16:"Ottakring",17:"Hernals",18:"Währing",19:"Döbling",20:"Brigittenau",21:"Floridsdorf",22:"Donaustadt",23:"Liesing"}
MON = ["JAN","FEB","MAR","APR","MAY","JUN","JUL","AUG","SEP","OCT","NOV","DEC"]

src = json.loads(pathlib.Path(sys.argv[1]).read_text())
geo = json.loads((ROOT / "data" / "vienna-districts.geo.json").read_text())
districts = []
for nr, rings in sorted(geo.items(), key=lambda kv: int(kv[0])):
    d = ""; xs = []; ys = []
    for ring in rings:
        pts = [((lng - LNG0) * KX, (LAT1 - lat) * KY) for lng, lat in ring]
        xs += [p[0] for p in pts]; ys += [p[1] for p in pts]
        d += "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z"
    districts.append({"nr": int(nr), "name": NAMES[int(nr)], "d": d, "cx": round(sum(xs) / len(xs), 1), "cy": round(sum(ys) / len(ys), 1)})
dots = [[int(v) / 10 for v in p.split(",")] for p in src["pts"].split(";")]
assert len(dots) == src["n"] == sum(n for _, n in src["months"])
months = []; i = 0
for m, n in src["months"]:
    months.append([i, f"{MON[int(m[5:]) - 1]} {m[:4]}"]); i += n
ts = "// Generated by scripts/places_data.py from " + sys.argv[1] + " — do not edit by hand.\n"
ts += "// Vienna Bezirke: data.wien.gv.at, CC BY 4.0, simplified.\n"
ts += f"export const PLACES = {{ date_en: {json.dumps(src['date_en'])}, n: {src['n']}, prices: {src['prices']} }};\n"
ts += f"export const PROJ = {{ lng0: {LNG0}, lat1: {LAT1}, kx: {KX}, ky: {KY} }};\n"
ts += "export const project = (lat: number, lng: number): [number, number] => [(lng - PROJ.lng0) * PROJ.kx, (PROJ.lat1 - lat) * PROJ.ky];\n"
ts += "export const BEZIRKE: { nr: number; name: string; d: string; cx: number; cy: number }[] = " + json.dumps(districts, ensure_ascii=False) + ";\n"
ts += "// one dot per place, in the order the first price was added\n"
ts += "export const DOTS: number[][] = " + json.dumps(dots) + ";\n"
ts += "// [index of the first dot of the month, label]\n"
ts += "export const MONTHS: [number, string][] = " + json.dumps(months) + ";\n"
(ROOT / "src" / "howmuch" / "places-data.ts").write_text(ts)
print(len(dots), "dots,", len(districts), "districts")
